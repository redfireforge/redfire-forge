/**
 * Opens the TLS modal if it is not already open.
 *
 * The Configure button (`data-testid="tls-toggle"`) never receives an
 * `aria-expanded` attribute, so checking that property always returns null.
 * Instead we check whether the modal body (`data-testid="tls-body"`) is
 * already present in the DOM — if so, the modal is open and we skip the click.
 */
async function ensureTlsPanelExpanded(ctx: DemoActionContext): Promise<void> {
  await ctx.waitFor(WS.TLS_TOGGLE, 2000);
  const alreadyOpen = !!document.querySelector(WS.TLS_BODY);
  if (!alreadyOpen) {
    const toggle = document.querySelector(WS.TLS_TOGGLE) as HTMLElement | null;
    if (toggle) {
      toggle.dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: true }));
      await ctx.delay(300);
    }
  }
}

/**
 * Closes the TLS modal if it is currently open, by clicking its Close button.
 * Must be called before connecting so the Connect tab is fully visible.
 */
async function closeTlsModal(ctx: DemoActionContext): Promise<void> {
  const closeBtn = document.querySelector('[data-testid="tls-close"]') as HTMLElement | null;
  if (closeBtn) {
    closeBtn.dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: true }));
    await ctx.delay(300);
  }
}

/**
 * Toggles the skip-cert checkbox to the desired state via a click dispatch.
 * React controlled checkboxes respond to click events: the click toggles the
 * DOM checked property and React's onClick handler fires, updating state.
 */
async function setSkipCert(ctx: DemoActionContext, checked: boolean): Promise<void> {
  await ctx.waitFor(`${WS.TLS_SKIP_CERT} input[type="checkbox"]`, 2000);
  const checkbox = document.querySelector(`${WS.TLS_SKIP_CERT} input[type="checkbox"]`) as HTMLInputElement | null;
  if (!checkbox || checkbox.checked === checked) return;
  checkbox.dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: true }));
  await ctx.delay(200);
}

/** Clears all three TLS PEM text fields (CA cert, client cert, client key). */
async function clearCertFields(ctx: DemoActionContext): Promise<void> {
  await ctx.fill(WS.TLS_CA_CERT, '');
  await ctx.fill(WS.TLS_CLIENT_CERT, '');
  await ctx.fill(WS.TLS_CLIENT_KEY, '');
  await ctx.delay(150);
}

// ── Setup / Cleanup ────────────────────────────────────────────────

async function localTlsSetup(ctx: DemoActionContext): Promise<void> {
  await ctx.delay(500);
  await ctx.click(WS.MODE_CLIENT);
  await ctx.delay(300);

  await disconnectWebSocket(ctx);
  await closeExtraConnectionTabs(ctx);
  await clearEvents(ctx);

  // Clear auth and custom headers — these trigger proxy mode and can cause 504s
  // when the Node.js backend is not running. We want a clean slate.
  await resetAuth(ctx);
  await clearCustomHeaders(ctx);

  await ctx.click(WS.LEFT_TAB_CONNECT);
  await ctx.delay(200);
  await ctx.click(WS.RIGHT_TAB_EVENTS);
  await ctx.delay(200);

  // Fill the wss:// URL to mount the TLS panel, reset its state, then CLEAR the
  // URL so step 1 shows the full "wss:// → TLS panel appears" moment visually.
  await ctx.fill(WS.URL_INPUT, TLS_URL);
  await ensureTlsPanelExpanded(ctx);
  await setSkipCert(ctx, false);
  await clearCertFields(ctx);
  await ctx.fill(WS.URL_INPUT, '');
  await ctx.delay(200);
}

async function localTlsCleanup(ctx: DemoActionContext): Promise<void> {
  await ctx.click(WS.MODE_CLIENT);
  await ctx.delay(300);
  await ctx.click(WS.LEFT_TAB_CONNECT);
  await ctx.delay(200);

  await disconnectWebSocket(ctx);
  await clearEvents(ctx);

  // Restore wss:// URL so the TLS panel renders, reset all state, then clear.
  await ctx.fill(WS.URL_INPUT, TLS_URL);
  await ensureTlsPanelExpanded(ctx);
  await setSkipCert(ctx, false);
  await clearCertFields(ctx);
  await ctx.fill(WS.URL_INPUT, '');
  await ctx.delay(200);
  await closeExtraConnectionTabs(ctx);
}

