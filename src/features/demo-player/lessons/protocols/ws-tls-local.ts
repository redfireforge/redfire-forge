/**
 * Lesson: Local TLS Echo Server (Docker)
 *
 * Three-phase TLS education against a REAL local server in Docker:
 *
 *  Phase 1 — Skip Certificate Validation (rejectUnauthorized: false)
 *    Steps 1–3: fill wss:// URL, enable skip-cert, connect via Proxy
 *
 *  Phase 2 — CA Certificate Validation (custom root CA, full chain)
 *    Steps 4–5: paste CA cert, reconnect via Proxy
 *
 *  Phase 3 — Mutual TLS / mTLS (client certificate authentication)
 *    Steps 6–8: switch to mTLS server (port 8768), paste client cert+key, connect
 *
 * Docker stack:
 *   TLS echo   → wss://localhost:8766  (Phase 1 + 2) [docker-compose.tls.yml]
 *   mTLS echo  → wss://localhost:8768  (Phase 3)     [docker-compose.mtls.yml]
 *
 * Health probes:
 *   http://localhost:8767  (Phase 1+2 gate — ws-echo-tls:8080 on host)
 *   http://localhost:8769  (Phase 3 — ws-echo-mtls:8080 on host)
 *
 * Prerequisites:
 *   cd docker/websocket
 *   ./generate-cert.sh         # creates CA + server certs (one-time)
 *   ./generate-client-cert.sh  # creates client.crt + client.key (one-time)
 *   docker compose -f docker-compose.tls.yml  up -d
 *   docker compose -f docker-compose.mtls.yml up -d
 */
